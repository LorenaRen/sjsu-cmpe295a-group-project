"""The benchmark's maps (pure Python).

narrow_aisle (mrs_sim) and samples_world (the checker's test map) are used as they are. The
large map, bench_grid, is generated here and committed as maps/bench_grid.yaml:

  rows x cols rooms of 6 x 6 m on a 10 m pitch. Each room has a centre node, four corner nodes
  and a door node on each side that has a neighbour; every node of a room is joined to its
  centre. Neighbouring rooms are joined door to door through a one-robot corridor (a narrow
  zone of capacity 1, 0.8 m wide, with no node of its own).

So a route through a room passes its centre, where S-4 can find two robots at once, and a route
from room to room uses a corridor, where S-1 can. No randomness: the same arguments always
give the same map.

    python -m bench.maps     # from benchmarks/: write maps/bench_grid.yaml again
"""
from __future__ import annotations

from typing import Any

import yaml

from fleet_checker.adapters.sim_map import SimMap, load_sim_map
from fleet_checker.plan import RegionKind

from . import config

PITCH, ROOM, HALF_CORRIDOR, DOOR_INSET = 10.0, 6.0, 0.4, 0.6
_HEADER = ("# Benchmark map, generated by benchmarks/bench/maps.py (bench_grid_map); do not edit by hand.\n"
           "# Regenerate with: cd code/mrs-ethics/benchmarks && python -m bench.maps\n")


def bench_grid_map(rows: int = 4, cols: int = 4) -> dict[str, Any]:
    """The large map as mrs_sim map data: room (i, j) is column i along x, row j along y."""
    nodes: dict[str, dict[str, float]] = {}
    edges: list[list[str]] = []
    zones: list[dict[str, Any]] = []

    def node(name: str, x: float, y: float) -> str:
        nodes[name] = {"x": x, "y": y}
        return name

    for i in range(cols):
        for j in range(rows):
            x0, y0, r = PITCH * i, PITCH * j, f"r{i}{j}"
            zones.append({"id": f"room_{i}{j}", "type": "room",
                          "rect": {"x_min": x0, "x_max": x0 + ROOM, "y_min": y0, "y_max": y0 + ROOM}})
            centre = node(f"{r}_c", x0 + ROOM / 2, y0 + ROOM / 2)
            corners = {"sw": (1.5, 1.5), "se": (4.5, 1.5), "nw": (1.5, 4.5), "ne": (4.5, 4.5)}
            doors = {"e": (ROOM - DOOR_INSET, ROOM / 2, i + 1 < cols), "w": (DOOR_INSET, ROOM / 2, i > 0),
                     "n": (ROOM / 2, ROOM - DOOR_INSET, j + 1 < rows), "s": (ROOM / 2, DOOR_INSET, j > 0)}
            for name, (dx, dy) in corners.items():
                edges.append([centre, node(f"{r}_{name}", x0 + dx, y0 + dy)])
            for name, (dx, dy, there) in doors.items():
                if there:
                    edges.append([centre, node(f"{r}_{name}", x0 + dx, y0 + dy)])
    for i in range(cols):
        for j in range(rows):
            x0, y0 = PITCH * i, PITCH * j
            if i + 1 < cols:
                edges.append([f"r{i}{j}_e", f"r{i + 1}{j}_w"])
                zones.append({"id": f"hall_{i}{j}_e", "type": "narrow", "capacity": 1,
                              "rect": {"x_min": x0 + ROOM, "x_max": x0 + PITCH,
                                       "y_min": y0 + ROOM / 2 - HALF_CORRIDOR, "y_max": y0 + ROOM / 2 + HALF_CORRIDOR}})
            if j + 1 < rows:
                edges.append([f"r{i}{j}_n", f"r{i}{j + 1}_s"])
                zones.append({"id": f"hall_{i}{j}_n", "type": "narrow", "capacity": 1,
                              "rect": {"x_min": x0 + ROOM / 2 - HALF_CORRIDOR, "x_max": x0 + ROOM / 2 + HALF_CORRIDOR,
                                       "y_min": y0 + ROOM, "y_max": y0 + PITCH}})
    corners = [f"r{i}{j}_c" for i, j in ((0, 0), (cols - 1, rows - 1), (0, rows - 1), (cols - 1, 0))]
    return {"world": "bench_grid",
            "description": f"Benchmark map: {cols} x {rows} rooms joined by one-robot corridors.",
            "nodes": nodes, "edges": edges, "zones": zones,
            "spawns": [{"node": n, "yaw": 0.0} for n in corners]}


def write_bench_grid() -> None:
    config.MAP_FILES["bench_grid"].write_text(
        _HEADER + yaml.safe_dump(bench_grid_map(), sort_keys=False, default_flow_style=None, width=120))


def load_maps() -> dict[str, SimMap]:
    return {name: load_sim_map(path) for name, path in config.MAP_FILES.items()}


def stoppable_nodes(sim_map: SimMap) -> list[str]:
    """Nodes in open areas: a robot may end its plan there without breaking P-1 (no stop in a
    narrow zone, doorway or keep-clear zone) or P-2 (restricted zones), so a benchmark plan's
    findings are conflicts between robots."""
    return sorted(n for n, zone in sim_map.zone_of.items()
                  if sim_map.world.regions[zone].kind == RegionKind.OPEN_AREA)


def halves(sim_map: SimMap, nodes: list[str]) -> tuple[list[str], list[str]]:
    """nodes split into a west and an east half, at the middle of their x range."""
    xs = [sim_map.positions[n][0] for n in nodes]
    middle = (min(xs) + max(xs)) / 2
    return ([n for n in nodes if sim_map.positions[n][0] < middle],
            [n for n in nodes if sim_map.positions[n][0] >= middle])


if __name__ == "__main__":
    write_bench_grid()
    print(f"wrote {config.MAP_FILES['bench_grid']}")
